/**
 * Writes the ADR 0014 gallery's scenario registry from whatever `*.scenario.ts` files
 * exist under `src/`.
 *
 * The ADR calls for Vite's `import.meta.glob`, which is how Playwright's own React and
 * Vue gallery examples discover their stories. That does not work here: the Angular
 * builder bundles with esbuild and never applies Vite's glob transform, so the call
 * survives into the bundle unexpanded and finds nothing. A generated registry of static
 * imports is the same idea — colocated scenarios, discovered rather than listed by hand
 * — through a mechanism this toolchain actually runs. It is regenerated by
 * `pnpm run gallery`, so it cannot drift from the files on disk.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const sourceRoot = join(root, 'src');
const target = join(root, 'playwright/gallery/scenarios.generated.ts');

function findScenarios(directory) {
  const found = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      found.push(...findScenarios(path));
    } else if (entry.name.endsWith('.scenario.ts')) {
      found.push(path);
    }
  }
  return found;
}

const scenarios = findScenarios(sourceRoot)
  .map((path) => relative(root, path).replaceAll('\\', '/'))
  .sort();

const imports = scenarios
  .map((path, index) => `import * as scenario${index} from '../../${path.replace(/\.ts$/, '')}';`)
  .join('\n');

const entries = scenarios.map((path, index) => `  '${path}': scenario${index},`).join('\n');

const contents = `/**
 * Generated from every \`*.scenario.ts\` under \`src/\` by
 * \`scripts/generate-scenarios.mjs\`. Committed, never hand-edited; \`pnpm run gallery\`
 * regenerates it before the dev server starts.
 */
${imports}

export const SCENARIO_MODULES: Readonly<Record<string, Record<string, unknown>>> = {
${entries}
};
`;

writeFileSync(target, contents, 'utf8');
console.log(`Wrote ${scenarios.length} scenario module(s) to ${relative(root, target)}`);

// Guard against a scenario file that exports nothing the harness can mount.
for (const path of scenarios) {
  if (!readFileSync(join(root, path), 'utf8').includes('export const')) {
    console.warn(`  ${path} has no exported scenario.`);
  }
}
